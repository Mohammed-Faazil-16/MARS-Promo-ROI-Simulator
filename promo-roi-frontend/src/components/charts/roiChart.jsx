import { useMemo, useState } from "react";

import {
  calculateScenario,
  money,
  number,
  roiLabel,
} from "../../utils/roiCalculations";

const METRICS = [
  { value: "roi", label: "ROI" },
  { value: "extraProfit", label: "Extra profit" },
  { value: "promoCost", label: "Promo cost" },
  { value: "uplift", label: "Sales uplift" },
];

function getMetricValue(result, metric) {
  switch (metric) {
    case "extraProfit":
      return result.extraProfit;
    case "promoCost":
      return result.promoCost;
    case "uplift":
      return result.uplift;
    case "roi":
    default:
      return result.roi;
  }
}

function formatMetricValue(value, metric) {
  if (!Number.isFinite(value)) return "—";

  switch (metric) {
    case "extraProfit":
    case "promoCost":
      return money(value);
    case "uplift":
      return `${value > 0 ? "+" : ""}${number(value)}%`;
    case "roi":
    default:
      return roiLabel(value);
  }
}

// Mars-inspired gradients for the scenario performance bars.
function getMetricColor(value, metric, verdict) {
  if (metric === "roi") {
    if (verdict === "Approve") {
      return "linear-gradient(90deg, #00A88F, #00D7B9)";
    }

    if (verdict === "Reject") {
      return "linear-gradient(90deg, #E52D27, #FF3C14)";
    }

    return "linear-gradient(90deg, #E5B900, #FFDC00)";
  }

  if (metric === "promoCost") {
    return "linear-gradient(90deg, #000080, #0000A0)";
  }

  if (value > 0) {
    return "linear-gradient(90deg, #00A88F, #00D7B9)";
  }

  if (value < 0) {
    return "linear-gradient(90deg, #E52D27, #FF3C14)";
  }

  return "linear-gradient(90deg, #E5B900, #FFDC00)";
}

function getMetricDescription(metric) {
  switch (metric) {
    case "extraProfit":
      return "Compare incremental profit generated by each promotion scenario.";
    case "promoCost":
      return "Compare the total discount investment required for each scenario.";
    case "uplift":
      return "Compare the percentage increase in weekly sales versus baseline.";
    case "roi":
    default:
      return "Compare return on promotion cost across your current scenarios.";
  }
}

function getMetricNote(metric) {
  switch (metric) {
    case "extraProfit":
      return "Positive values indicate incremental profit; negative values indicate profit erosion.";
    case "promoCost":
      return "Promotion investment is shown as total discount cost over the scenario duration.";
    case "uplift":
      return "Sales uplift compares promotional units per week with baseline units per week.";
    case "roi":
    default:
      return "Decision thresholds: Approve ≥ 20% · Review 0–19.9% · Reject below 0%.";
  }
}

/**
 * Single Dashboard chart with selectable performance measures.
 * Reuses the existing scenario calculation utility and Dashboard metrics.
 */
export default function ROIChart({
  scenarios = [],
  title = "Scenario performance",
  description = "Compare the financial performance of your promotion scenarios.",
  maxItems = 6,
}) {
  const [selectedMetric, setSelectedMetric] = useState("roi");

  const rows = useMemo(
    () =>
      scenarios.slice(0, maxItems).map((scenario) => {
        const result = calculateScenario(scenario);
        return {
          scenario,
          result,
          value: getMetricValue(result, selectedMetric),
        };
      }),
    [scenarios, maxItems, selectedMetric],
  );

  const maxAbsValue = Math.max(
    1,
    ...rows.map(({ value }) =>
      Number.isFinite(value) ? Math.abs(value) : 0,
    ),
  );

  const metricLabel =
    METRICS.find((metric) => metric.value === selectedMetric)?.label ?? "ROI";
  const displayTitle =
    selectedMetric === "roi" ? title : `${metricLabel} by scenario`;
  const displayDescription =
    selectedMetric === "roi"
      ? description
      : getMetricDescription(selectedMetric);

  return (
    <section className="table-card roi-chart-card" aria-label={displayTitle}>
      <div className="table-card-header roi-chart-header">
        <div>
          <h2>{displayTitle}</h2>
          <p>{displayDescription}</p>
        </div>

        <label className="roi-metric-control">
          <span>View</span>
          <select
            className="filter-select roi-metric-select"
            value={selectedMetric}
            onChange={(event) => setSelectedMetric(event.target.value)}
            aria-label="Choose scenario performance metric"
          >
            {METRICS.map((metric) => (
              <option key={metric.value} value={metric.value}>
                {metric.label}
              </option>
            ))}
          </select>
        </label>
      </div>

      {rows.length === 0 ? (
        <div className="roi-chart-empty">
          No scenarios available to chart yet.
        </div>
      ) : (
        <div className="roi-chart" style={{ display: "grid", gap: 18 }}>
          {rows.map(({ scenario, result, value }) => {
            const safeValue = Number.isFinite(value) ? value : 0;
            const width = Math.min(
              100,
              (Math.abs(safeValue) / maxAbsValue) * 100,
            );
            const barColor = getMetricColor(
              safeValue,
              selectedMetric,
              result.verdict,
            );

            return (
              <div
                className="roi-chart-row"
                key={scenario.id}
                title={`${scenario.name}: ${formatMetricValue(
                  safeValue,
                  selectedMetric,
                )}`}
                style={{
                  display: "grid",
                  gridTemplateColumns:
                    "minmax(120px, 1.1fr) minmax(80px, 2fr) minmax(76px, auto)",
                  alignItems: "center",
                  gap: 12,
                }}
              >
                <div className="roi-chart-label" style={{ minWidth: 0 }}>
                  <div className="roi-chart-name">{scenario.name}</div>
                  <div className="roi-chart-product">
                    {scenario.product || "Product not specified"}
                  </div>
                </div>

                <div
                  className="roi-track"
                  role="img"
                  aria-label={`${scenario.name}: ${formatMetricValue(
                    safeValue,
                    selectedMetric,
                  )} ${metricLabel}`}
                  style={{
                    height: 10,
                    backgroundColor: "#E9E8F2",
                    borderRadius: 999,
                    overflow: "hidden",
                  }}
                >
                  <div
                    className="roi-track-bar"
                    style={{
                      width: `${Math.max(2, width)}%`,
                      height: "100%",
                      borderRadius: 999,
                      background: barColor,
                      transition: "width 700ms ease, background 400ms ease",
                      boxShadow: "0 2px 6px rgba(0, 0, 160, 0.12)",
                    }}
                  />
                </div>

                <strong
                  className={`roi-chart-value ${
                    safeValue < 0 ? "roi-negative" : "roi-positive"
                  }`}
                  style={{
                    fontSize: 13,
                    textAlign: "right",
                    fontVariantNumeric: "tabular-nums",
                    color: safeValue < 0 ? "#E52D27" : "#292d2a",
                  }}
                >
                  {formatMetricValue(safeValue, selectedMetric)}
                </strong>
              </div>
            );
          })}
        </div>
      )}

      <footer className="roi-chart-footer">
        <span>Bar length is relative to the largest absolute value in this view.</span>
        <span>{getMetricNote(selectedMetric)}</span>
      </footer>
    </section>
  );
}
